let a = 75;

if (a >= 90 && a <= 100) {
    console.log("Grade is A");
}
else if (a >= 80 && a <= 89) {
    console.log("Grade is B");
}
else if (a >= 70 && a <= 79) {
    console.log("Grade is C");
}
else if (a >= 60 && a <= 69) {
    console.log("Grade is D");
}
else if (a >= 0 && a <= 59) {
    console.log("Grade is F");
}
else {
    console.log("Invalid marks");
}